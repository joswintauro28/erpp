import type { ParsedCss, CssVariable, VariableType } from "./css-parser";

function v(name: string, value: string, line: number): CssVariable {
  let type: VariableType = "other";
  if (/^#[0-9A-Fa-f]{3,8}$/.test(value)) type = "color";
  else if (/^(rgb|rgba|hsla?|oklch|color-mix)\s*\(/.test(value)) type = "color";
  else if (/^var\s*\(/.test(value)) type = "reference";
  else if (/^calc\s*\(/.test(value)) type = "calc";
  else if (/^-?\d+(\.\d+)?(px|rem|em|pt|vh|vw|vmin|vmax|ch|ex|cm|mm|in)$/i.test(value)) type = "size";
  else if (/["']?.+["']?,\s*(sans-serif|serif|monospace|cursive|fantasy)$/i.test(value)) type = "font";
  return { name, cssVar: `--${name}`, value, type, line };
}

