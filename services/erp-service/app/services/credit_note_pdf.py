import os
import tempfile
from datetime import datetime
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas

BRAND_DARK = colors.HexColor("#0f172a")
BRAND_ACCENT = colors.HexColor("#3b82f6")
TEXT_PRIMARY = colors.HexColor("#1e293b")
TEXT_MUTED = colors.HexColor("#64748b")

def _fmt(val):
    v = float(val or 0)
    return f"{v:,.2f}"

def build_credit_note_pdf(cn, company, branding):
    fd, temp_path = tempfile.mkstemp(suffix=".pdf")
    os.close(fd)
    
    width, height = A4
    c = canvas.Canvas(temp_path, pagesize=A4)
    
    # Header
    c.setFillColor(BRAND_DARK)
    c.rect(0, height - 28 * mm, width, 28 * mm, fill=1, stroke=0)
    
    c.setFillColor(colors.white)
    c.setFont("Helvetica-Bold", 16)
    c.drawString(15 * mm, height - 15 * mm, company.get("company_name") or "Your Company")
    
    c.setFont("Helvetica", 10)
    c.drawRightString(width - 15 * mm, height - 15 * mm, f"CREDIT NOTE: {cn['credit_note_number']}")
    
    # Meta Info
    c.setFillColor(TEXT_PRIMARY)
    c.setFont("Helvetica-Bold", 12)
    c.drawString(15 * mm, height - 40 * mm, "CREDIT NOTE TO:")
    
    c.setFont("Helvetica", 10)
    y = height - 46 * mm
    c.drawString(15 * mm, y, cn.get("client_name") or "Unknown Client")
    if cn.get("client_email"):
        y -= 5 * mm
        c.drawString(15 * mm, y, cn.get("client_email"))
        
    c.setFont("Helvetica-Bold", 10)
    c.drawRightString(width - 15 * mm, height - 40 * mm, "Adjustment Details")
    c.setFont("Helvetica", 10)
    c.drawRightString(width - 15 * mm, height - 46 * mm, f"Date: {cn['issue_date']}")
    c.drawRightString(width - 15 * mm, height - 51 * mm, f"Original Invoice: {cn['invoice_number']}")
    if cn['restock_items']:
        c.drawRightString(width - 15 * mm, height - 56 * mm, "Items Restocked: Yes")

    items = cn.get("items", [])
    
    if not items:
        # Legacy Credit Note
        c.setFillColor(BRAND_DARK)
        c.rect(15 * mm, height - 75 * mm, width - 30 * mm, 8 * mm, fill=1, stroke=0)
        c.setFillColor(colors.white)
        c.setFont("Helvetica-Bold", 10)
        c.drawString(20 * mm, height - 72 * mm, "Reason for Credit")
        c.drawRightString(width - 20 * mm, height - 72 * mm, "Amount")
        
        c.setFillColor(TEXT_PRIMARY)
        c.setFont("Helvetica", 10)
        c.drawString(20 * mm, height - 85 * mm, cn['reason'] + " (Legacy Credit Note)")
        c.setFont("Helvetica-Bold", 12)
        c.drawRightString(width - 20 * mm, height - 85 * mm, f"Rs. {_fmt(cn['amount'])}")
    else:
        # Itemized Credit Note
        c.setFillColor(BRAND_DARK)
        c.rect(15 * mm, height - 75 * mm, width - 30 * mm, 8 * mm, fill=1, stroke=0)
        c.setFillColor(colors.white)
        c.setFont("Helvetica-Bold", 10)
        c.drawString(20 * mm, height - 72 * mm, "Product")
        c.drawRightString(width - 100 * mm, height - 72 * mm, "Original Qty")
        c.drawRightString(width - 70 * mm, height - 72 * mm, "Returned Qty")
        c.drawRightString(width - 45 * mm, height - 72 * mm, "Rate")
        c.drawRightString(width - 20 * mm, height - 72 * mm, "Line Total")
        
        y = height - 85 * mm
        c.setFillColor(TEXT_PRIMARY)
        c.setFont("Helvetica", 9)
        for item in items:
            c.drawString(20 * mm, y, str(item['product_name'])[:40])
            c.drawRightString(width - 100 * mm, y, str(item['original_quantity']))
            c.drawRightString(width - 70 * mm, y, str(item['returned_quantity']))
            c.drawRightString(width - 45 * mm, y, _fmt(item['unit_price']))
            c.drawRightString(width - 20 * mm, y, _fmt(item['line_total']))
            y -= 6 * mm
            
        # Total line
        y -= 4 * mm
        c.setFont("Helvetica-Bold", 10)
        c.drawString(20 * mm, y, f"Reason: {cn['reason']}")
        
        c.setFont("Helvetica-Bold", 12)
        c.drawRightString(width - 20 * mm, y, f"Total Credit: Rs. {_fmt(cn['amount'])}")

    # Footer
    c.setFont("Helvetica", 7)
    c.setFillColor(TEXT_MUTED)
    c.drawString(15 * mm, 8 * mm, f"Generated by VexBill on {datetime.now().strftime('%d %b %Y')}")
    
    c.save()
    return temp_path
