"""
VexBill PDF Generator Service
Generates professional PDF exports for:
  - Invoices (redesigned)
  - Profit & Loss Statement
  - Balance Sheet
  - Cash Flow Statement
  - Trial Balance
"""
import os
import tempfile
import textwrap
from datetime import date, datetime
from decimal import Decimal

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas


# ──────────────────────────── Shared Helpers ─────────────────────────────

BRAND_DARK = colors.HexColor("#0f172a")
BRAND_ACCENT = colors.HexColor("#3b82f6")
BRAND_LIGHT_BG = colors.HexColor("#f8fafc")
BRAND_BORDER = colors.HexColor("#e2e8f0")
TEXT_PRIMARY = colors.HexColor("#1e293b")
TEXT_MUTED = colors.HexColor("#64748b")


def _fmt(val):
    """Format a number as Indian Rupee currency."""
    v = float(val or 0)
    if v < 0:
        return f"({abs(v):,.2f})"
    return f"{v:,.2f}"


def _rupee(val):
    return f"Rs. {_fmt(val)}"


def _draw_page_footer(c, width, page_num, report_title=""):
    c.setFont("Helvetica", 7)
    c.setFillColor(TEXT_MUTED)
    c.drawString(15 * mm, 8 * mm, f"Generated by VexBill on {datetime.now().strftime('%d %b %Y, %I:%M %p')}")
    if report_title:
        c.drawCentredString(width / 2, 8 * mm, report_title)
    c.drawRightString(width - 15 * mm, 8 * mm, f"Page {page_num}")


def _draw_report_header(c, width, height, company_name, report_title, period_text):
    """Draw a professional report header with company name and period."""
    # Dark header bar
    c.setFillColor(BRAND_DARK)
    c.rect(0, height - 28 * mm, width, 28 * mm, fill=1, stroke=0)

    # Company name
    c.setFillColor(colors.white)
    c.setFont("Helvetica-Bold", 18)
    c.drawString(15 * mm, height - 14 * mm, str(company_name or "VexBill")[:50])

    # Report title
    c.setFont("Helvetica", 11)
    c.drawRightString(width - 15 * mm, height - 12 * mm, report_title)

    # Period
    c.setFont("Helvetica", 9)
    c.drawRightString(width - 15 * mm, height - 18 * mm, period_text)

    return height - 38 * mm


# ──────────────────────── INVOICE PDF (Redesigned) ───────────────────────

def build_invoice_pdf(invoice, company, branding, items):
    """Build a professional commercial-grade invoice PDF."""
    pdf_file = os.path.join(tempfile.gettempdir(), f"vexbill_invoice_{invoice.get('id', 0)}.pdf")
    c = canvas.Canvas(pdf_file, pagesize=A4)
    w, h = A4
    m = 15 * mm  # margin
    page_num = 1

    primary_color = colors.HexColor((branding.get("primary_color") or "#0f172a")[:7])

    # ── HEADER BAR ──
    c.setFillColor(primary_color)
    c.rect(0, h - 32 * mm, w, 32 * mm, fill=1, stroke=0)

    c.setFillColor(colors.white)
    c.setFont("Helvetica-Bold", 20)
    c.drawString(m, h - 15 * mm, str(company.get("company_name") or "VexBill")[:40])

    c.setFont("Helvetica", 8)
    addr = str(company.get("address") or "")[:60]
    c.drawString(m, h - 21 * mm, addr)
    email_line = str(company.get("email") or "")
    phone_line = str(company.get("phone") or "")
    contact = f"{email_line}  |  {phone_line}".strip(" |")
    c.drawString(m, h - 26 * mm, contact)

    c.setFont("Helvetica-Bold", 16)
    c.drawRightString(w - m, h - 15 * mm, "TAX INVOICE")
    c.setFont("Helvetica", 9)
    c.drawRightString(w - m, h - 21 * mm, str(invoice.get("invoice_number") or ""))
    comp_gst = company.get("gst_number") or ""
    if comp_gst:
        c.drawRightString(w - m, h - 26 * mm, f"GSTIN: {comp_gst}")

    y = h - 40 * mm

    # ── BILL TO / INVOICE DETAILS ──
    c.setFillColor(BRAND_LIGHT_BG)
    c.rect(m, y - 30 * mm, w - 2 * m, 30 * mm, fill=1, stroke=0)
    c.setStrokeColor(BRAND_BORDER)
    c.rect(m, y - 30 * mm, w - 2 * m, 30 * mm, fill=0, stroke=1)

    # Left: Bill To
    bx = m + 5 * mm
    by = y - 5 * mm
    c.setFillColor(TEXT_MUTED)
    c.setFont("Helvetica", 7)
    c.drawString(bx, by, "BILL TO")
    c.setFillColor(TEXT_PRIMARY)
    c.setFont("Helvetica-Bold", 10)
    c.drawString(bx, by - 5 * mm, str(invoice.get("client_name") or "")[:40])
    c.setFont("Helvetica", 8)
    c.drawString(bx, by - 10 * mm, str(invoice.get("client_email") or ""))
    client_gst = invoice.get("client_gst_number") or ""
    if client_gst:
        c.drawString(bx, by - 15 * mm, f"GSTIN: {client_gst}")
    c.drawString(bx, by - 20 * mm, str(invoice.get("client_address") or "")[:50])

    # Right: Invoice Details
    rx = w / 2 + 10 * mm
    c.setFillColor(TEXT_MUTED)
    c.setFont("Helvetica", 7)
    c.drawString(rx, by, "INVOICE DETAILS")
    c.setFillColor(TEXT_PRIMARY)
    c.setFont("Helvetica", 9)
    details = [
        ("Issue Date:", str(invoice.get("issue_date") or "")),
        ("Due Date:", str(invoice.get("due_date") or "N/A")),
        ("Status:", (invoice.get("computed_status") or invoice.get("status") or "pending").upper()),
        ("GST Treatment:", str(invoice.get("gst_treatment") or "intrastate").title()),
    ]
    dy = by - 5 * mm
    for label, val in details:
        c.setFont("Helvetica", 8)
        c.setFillColor(TEXT_MUTED)
        c.drawString(rx, dy, label)
        c.setFillColor(TEXT_PRIMARY)
        c.setFont("Helvetica-Bold", 8)
        c.drawString(rx + 25 * mm, dy, val)
        dy -= 5 * mm

    y = y - 38 * mm

    # ── ITEM TABLE ──
    col_widths = [52*mm, 12*mm, 20*mm, 12*mm, 22*mm, 16*mm, 16*mm, 16*mm, 22*mm]
    headers = ["Item", "Qty", "Rate", "GST%", "Taxable", "CGST", "SGST", "IGST", "Total"]
    xs = [m]
    for cw in col_widths[:-1]:
        xs.append(xs[-1] + cw)

    def draw_table_header(current_y):
        # Header row background
        c.setFillColor(BRAND_DARK)
        c.rect(m, current_y - 6 * mm, w - 2 * m, 7 * mm, fill=1, stroke=0)
        c.setFillColor(colors.white)
        c.setFont("Helvetica-Bold", 7)
        for i, hdr in enumerate(headers):
            if i == 0:
                c.drawString(xs[i] + 2 * mm, current_y - 4 * mm, hdr)
            else:
                c.drawRightString(xs[i] + col_widths[i] - 2 * mm, current_y - 4 * mm, hdr)
        return current_y - 8 * mm

    y = draw_table_header(y)

    # Item rows
    c.setFont("Helvetica", 7.5)
    row_idx = 0
    for item in items:
        desc = str(item.get("description") or item.get("product_name") or "")
        lines = textwrap.wrap(desc, width=38) or [""]
        row_h = max(len(lines) * 3.5 * mm, 5 * mm) + 2 * mm

        if y - row_h < 30 * mm:
            _draw_page_footer(c, w, page_num, "Tax Invoice")
            page_num += 1
            c.showPage()
            y = h - 15 * mm
            y = draw_table_header(y)
            c.setFont("Helvetica", 7.5)

        # Alternate row background
        if row_idx % 2 == 0:
            c.setFillColor(BRAND_LIGHT_BG)
            c.rect(m, y - row_h + 2 * mm, w - 2 * m, row_h, fill=1, stroke=0)

        c.setFillColor(TEXT_PRIMARY)
        ty = y
        for line in lines:
            c.drawString(xs[0] + 2 * mm, ty, line)
            ty -= 3.5 * mm

        val_y = y
        c.drawRightString(xs[1] + col_widths[1] - 2*mm, val_y, str(item.get("quantity") or 0))
        c.drawRightString(xs[2] + col_widths[2] - 2*mm, val_y, _fmt(item.get("unit_price")))
        c.drawRightString(xs[3] + col_widths[3] - 2*mm, val_y, f"{item.get('gst_rate') or 0}%")
        c.drawRightString(xs[4] + col_widths[4] - 2*mm, val_y, _fmt(item.get("taxable_amount")))
        c.drawRightString(xs[5] + col_widths[5] - 2*mm, val_y, _fmt(item.get("cgst")))
        c.drawRightString(xs[6] + col_widths[6] - 2*mm, val_y, _fmt(item.get("sgst")))
        c.drawRightString(xs[7] + col_widths[7] - 2*mm, val_y, _fmt(item.get("igst")))
        c.drawRightString(xs[8] + col_widths[8] - 2*mm, val_y, _fmt(item.get("total")))

        y -= row_h
        row_idx += 1

    # Bottom line
    c.setStrokeColor(BRAND_BORDER)
    c.line(m, y + 1 * mm, w - m, y + 1 * mm)
    y -= 6 * mm

    # ── SUMMARY SECTION ──
    if y < 60 * mm:
        _draw_page_footer(c, w, page_num, "Tax Invoice")
        page_num += 1
        c.showPage()
        y = h - 20 * mm

    summary_x = w / 2 + 15 * mm
    summary_w = w - m - summary_x

    totals = [
        ("Subtotal", invoice.get("subtotal"), False),
        ("CGST", invoice.get("cgst"), False),
        ("SGST", invoice.get("sgst"), False),
        ("IGST", invoice.get("igst"), False),
    ]

    c.setFont("Helvetica", 9)
    for label, val, bold in totals:
        if float(val or 0) > 0 or label == "Subtotal":
            c.setFillColor(TEXT_MUTED)
            c.drawString(summary_x, y, label)
            c.setFillColor(TEXT_PRIMARY)
            c.drawRightString(w - m, y, _rupee(val))
            y -= 5 * mm

    # Grand Total highlight
    y -= 2 * mm
    c.setFillColor(BRAND_DARK)
    c.rect(summary_x - 3 * mm, y - 4 * mm, summary_w + 6 * mm, 9 * mm, fill=1, stroke=0)
    c.setFillColor(colors.white)
    c.setFont("Helvetica-Bold", 11)
    c.drawString(summary_x, y, "Grand Total")
    c.drawRightString(w - m, y, _rupee(invoice.get("total")))
    y -= 12 * mm

    # Paid / Balance Due
    c.setFillColor(TEXT_PRIMARY)
    c.setFont("Helvetica", 9)
    c.drawString(summary_x, y, "Paid Amount")
    c.drawRightString(w - m, y, _rupee(invoice.get("paid_amount")))
    y -= 5 * mm

    balance = float(invoice.get("balance_due") or 0)
    c.setFont("Helvetica-Bold", 10)
    c.setFillColor(colors.HexColor("#dc2626") if balance > 0 else colors.HexColor("#16a34a"))
    c.drawString(summary_x, y, "Balance Due")
    c.drawRightString(w - m, y, _rupee(balance))
    y -= 10 * mm

    # ── NOTES ──
    notes = invoice.get("notes") or ""
    if notes:
        c.setFillColor(TEXT_PRIMARY)
        c.setFont("Helvetica-Bold", 8)
        c.drawString(m, y, "Notes:")
        c.setFont("Helvetica", 7.5)
        y -= 4 * mm
        for nline in textwrap.wrap(notes, width=90):
            c.drawString(m, y, nline)
            y -= 3.5 * mm

    # ── FOOTER ──
    c.setStrokeColor(BRAND_BORDER)
    c.line(m, 22 * mm, w - m, 22 * mm)

    c.setFillColor(TEXT_MUTED)
    c.setFont("Helvetica", 8)
    c.drawCentredString(w / 2, 17 * mm, "Thank you for your business!")

    footer_text = branding.get("invoice_footer") or "This is a computer-generated invoice. No signature required."
    c.setFont("Helvetica-Oblique", 7)
    c.drawCentredString(w / 2, 13 * mm, footer_text)

    _draw_page_footer(c, w, page_num, "Tax Invoice")
    c.save()
    return pdf_file


# ──────────────────────── REPORT PDF BUILDERS ────────────────────────────

def _build_report_table(c, y, w, h, m, headers, rows, col_widths, page_num, report_title, right_align_cols=None):
    """Generic table renderer for report PDFs. Returns (y, page_num)."""
    if right_align_cols is None:
        right_align_cols = set(range(1, len(headers)))  # all but first column right-aligned

    xs = [m]
    for cw in col_widths[:-1]:
        xs.append(xs[-1] + cw)

    # Header row
    c.setFillColor(BRAND_DARK)
    c.rect(m, y - 6 * mm, w - 2 * m, 7 * mm, fill=1, stroke=0)
    c.setFillColor(colors.white)
    c.setFont("Helvetica-Bold", 8)
    for i, hdr in enumerate(headers):
        if i in right_align_cols:
            c.drawRightString(xs[i] + col_widths[i] - 3 * mm, y - 4 * mm, hdr)
        else:
            c.drawString(xs[i] + 2 * mm, y - 4 * mm, hdr)
    y -= 9 * mm

    # Data rows
    for row_idx, row_data in enumerate(rows):
        if y < 22 * mm:
            _draw_page_footer(c, w, page_num, report_title)
            page_num += 1
            c.showPage()
            y = h - 15 * mm
            # Redraw header
            c.setFillColor(BRAND_DARK)
            c.rect(m, y - 6 * mm, w - 2 * m, 7 * mm, fill=1, stroke=0)
            c.setFillColor(colors.white)
            c.setFont("Helvetica-Bold", 8)
            for i, hdr in enumerate(headers):
                if i in right_align_cols:
                    c.drawRightString(xs[i] + col_widths[i] - 3 * mm, y - 4 * mm, hdr)
                else:
                    c.drawString(xs[i] + 2 * mm, y - 4 * mm, hdr)
            y -= 9 * mm

        is_bold = row_data.get("_bold", False)
        is_separator = row_data.get("_separator", False)

        if is_separator:
            c.setStrokeColor(BRAND_BORDER)
            c.line(m, y + 3 * mm, w - m, y + 3 * mm)
            y -= 1 * mm
            continue

        # Alternate row shading
        if row_idx % 2 == 0 and not is_bold:
            c.setFillColor(BRAND_LIGHT_BG)
            c.rect(m, y - 2 * mm, w - 2 * m, 6 * mm, fill=1, stroke=0)

        if is_bold:
            c.setFillColor(colors.HexColor("#f1f5f9"))
            c.rect(m, y - 2 * mm, w - 2 * m, 6 * mm, fill=1, stroke=0)

        font = "Helvetica-Bold" if is_bold else "Helvetica"
        c.setFont(font, 8)
        c.setFillColor(TEXT_PRIMARY)

        values = row_data.get("_values", [])
        for i, val in enumerate(values):
            if i in right_align_cols:
                c.drawRightString(xs[i] + col_widths[i] - 3 * mm, y, str(val))
            else:
                indent = row_data.get("_indent", 0) if i == 0 else 0
                c.drawString(xs[i] + 2 * mm + indent * mm, y, str(val))

        y -= 6 * mm

    return y, page_num


def build_profit_loss_pdf(data, company_name, period_text):
    pdf_file = os.path.join(tempfile.gettempdir(), "vexbill_profit_loss.pdf")
    c = canvas.Canvas(pdf_file, pagesize=A4)
    w, h = A4
    m = 15 * mm
    page_num = 1

    y = _draw_report_header(c, w, h, company_name, "Profit & Loss Statement", period_text)

    headers = ["Account", "Amount (Rs.)"]
    col_widths = [120 * mm, 60 * mm]

    rows = []
    # Revenue section
    rows.append({"_values": ["REVENUE", ""], "_bold": True})
    for item in data.get("revenue", []):
        rows.append({"_values": [item["name"], _fmt(item["amount"])], "_indent": 4})
    rows.append({"_values": ["Total Revenue", _fmt(data.get("total_revenue", 0))], "_bold": True})
    rows.append({"_separator": True})

    # COGS
    if data.get("cogs"):
        rows.append({"_values": ["COST OF GOODS SOLD", ""], "_bold": True})
        for item in data.get("cogs", []):
            rows.append({"_values": [item["name"], _fmt(item["amount"])], "_indent": 4})
        rows.append({"_values": ["Total COGS", _fmt(data.get("total_cogs", 0))], "_bold": True})
        rows.append({"_separator": True})

    rows.append({"_values": ["GROSS PROFIT", _fmt(data.get("gross_profit", 0))], "_bold": True})
    rows.append({"_separator": True})

    # Operating Expenses
    rows.append({"_values": ["OPERATING EXPENSES", ""], "_bold": True})
    for item in data.get("operating_expenses", []):
        rows.append({"_values": [item["name"], _fmt(item["amount"])], "_indent": 4})
    rows.append({"_values": ["Total Operating Expenses", _fmt(data.get("total_operating", 0))], "_bold": True})
    rows.append({"_separator": True})

    # Net Profit
    net = data.get("net_profit", 0)
    rows.append({"_values": ["NET PROFIT", _fmt(net)], "_bold": True})

    y, page_num = _build_report_table(c, y, w, h, m, headers, rows, col_widths, page_num, "Profit & Loss")

    # Net Profit Margin
    y -= 5 * mm
    margin = data.get("net_profit_margin", 0)
    c.setFont("Helvetica-Bold", 9)
    c.setFillColor(TEXT_PRIMARY)
    c.drawString(m, y, f"Net Profit Margin: {margin:.2f}%")

    _draw_page_footer(c, w, page_num, "Profit & Loss Statement")
    c.save()
    return pdf_file


def build_balance_sheet_pdf(data, company_name, period_text):
    pdf_file = os.path.join(tempfile.gettempdir(), "vexbill_balance_sheet.pdf")
    c = canvas.Canvas(pdf_file, pagesize=A4)
    w, h = A4
    m = 15 * mm
    page_num = 1

    y = _draw_report_header(c, w, h, company_name, "Balance Sheet", period_text)

    headers = ["Account", "Amount (Rs.)"]
    col_widths = [120 * mm, 60 * mm]

    assets = data.get("assets", {})
    liabilities = data.get("liabilities", {})
    equity = data.get("equity", {})

    rows = []
    # Assets
    rows.append({"_values": ["ASSETS", ""], "_bold": True})
    rows.append({"_values": ["Current Assets", ""], "_bold": True, "_indent": 2})
    for item in assets.get("current", []):
        rows.append({"_values": [item["name"], _fmt(item["amount"])], "_indent": 6})
    rows.append({"_values": ["Total Current Assets", _fmt(assets.get("total_current", 0))], "_bold": True, "_indent": 2})

    if assets.get("fixed"):
        rows.append({"_values": ["Fixed Assets", ""], "_bold": True, "_indent": 2})
        for item in assets.get("fixed", []):
            rows.append({"_values": [item["name"], _fmt(item["amount"])], "_indent": 6})
        rows.append({"_values": ["Total Fixed Assets", _fmt(assets.get("total_fixed", 0))], "_bold": True, "_indent": 2})

    rows.append({"_values": ["TOTAL ASSETS", _fmt(assets.get("total", 0))], "_bold": True})
    rows.append({"_separator": True})

    # Liabilities
    rows.append({"_values": ["LIABILITIES", ""], "_bold": True})
    rows.append({"_values": ["Current Liabilities", ""], "_bold": True, "_indent": 2})
    for item in liabilities.get("current", []):
        rows.append({"_values": [item["name"], _fmt(item["amount"])], "_indent": 6})
    rows.append({"_values": ["Total Current Liabilities", _fmt(liabilities.get("total_current", 0))], "_bold": True, "_indent": 2})
    rows.append({"_values": ["TOTAL LIABILITIES", _fmt(liabilities.get("total", 0))], "_bold": True})
    rows.append({"_separator": True})

    # Equity
    rows.append({"_values": ["EQUITY", ""], "_bold": True})
    for item in equity.get("items", []):
        rows.append({"_values": [item["name"], _fmt(item["amount"])], "_indent": 4})
    rows.append({"_values": ["TOTAL EQUITY", _fmt(equity.get("total", 0))], "_bold": True})
    rows.append({"_separator": True})

    # Balance Check
    total_le = float(liabilities.get("total", 0)) + float(equity.get("total", 0))
    rows.append({"_values": ["TOTAL LIABILITIES + EQUITY", _fmt(total_le)], "_bold": True})

    y, page_num = _build_report_table(c, y, w, h, m, headers, rows, col_widths, page_num, "Balance Sheet")

    _draw_page_footer(c, w, page_num, "Balance Sheet")
    c.save()
    return pdf_file


