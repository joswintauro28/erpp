def build_trial_balance_pdf(data, company_name, period_text):
    pdf_file = os.path.join(tempfile.gettempdir(), "vexbill_trial_balance.pdf")
    c = canvas.Canvas(pdf_file, pagesize=A4)
    w, h = A4
    m = 15 * mm
    page_num = 1

    y = _draw_report_header(c, w, h, company_name, "Trial Balance", period_text)

    headers = ["Account", "Debit (Rs.)", "Credit (Rs.)"]
    col_widths = [90 * mm, 45 * mm, 45 * mm]

    rows = []
    for acc in data.get("accounts", []):
        rows.append({"_values": [acc["account"], _fmt(acc["debit"]), _fmt(acc["credit"])]})

    rows.append({"_separator": True})
    rows.append({
        "_values": ["TOTAL", _fmt(data.get("total_debit", 0)), _fmt(data.get("total_credit", 0))],
        "_bold": True
    })

    balanced = data.get("balanced", False)
    rows.append({"_separator": True})
    status = "BALANCED" if balanced else "NOT BALANCED"
    rows.append({"_values": [f"Status: {status}", "", ""], "_bold": True})

